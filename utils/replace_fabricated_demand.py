"""
Replace fabricated demand rows with REAL Grid-India PSP data.

Rows dated on/after 2024-04-29 in the demand files were generated by the (now
removed) gap-fill scripts, or by an old ingestion fallback, and are NOT real.
This script removes every such row and inserts rows parsed from the real daily
PSP reports in ``data/psp/``. Dates without a parseable report stay absent;
nothing is interpolated.

Files rewritten (schema and column order are preserved):
  data/daily_energy_met_MU.csv, data/14983362/daily_energy_met_MU.csv,
  data/State_mu/state_mu_1.csv, data/State_mu/state_mu_2.csv,
  data/processed/long_state_mu2.csv

Usage:  python utils/replace_fabricated_demand.py [--dry-run]
"""

import argparse
import logging
import sys
from pathlib import Path
from typing import Tuple

import numpy as np
import pandas as pd

ROOT_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT_DIR))

from utils.parse_psp_reports import parse_all_psp_files  # noqa: E402

logger = logging.getLogger("replace_fabricated_demand")

FIRST_FABRICATED_DATE = "2024-04-29"
MIN_STATES_WITH_ENERGY = 30
MAX_STATE_SUM_DEVIATION = 0.05  # |sum(states)/Total - 1| above this flags a date for review

DEMAND_CSV_MAIN = ROOT_DIR / "data" / "daily_energy_met_MU.csv"
DEMAND_CSV_MIRROR = ROOT_DIR / "data" / "14983362" / "daily_energy_met_MU.csv"
STATE_MU_1_PATH = ROOT_DIR / "data" / "State_mu" / "state_mu_1.csv"
STATE_MU_2_PATH = ROOT_DIR / "data" / "State_mu" / "state_mu_2.csv"
LONG_STATE_MU2_PATH = ROOT_DIR / "data" / "processed" / "long_state_mu2.csv"

GEN_REGION_COLS = ["NR", "WR", "SR", "ER", "NER", "All India"]


def _write_csv(df: pd.DataFrame, path: Path) -> None:
    df.to_csv(path, index=False, lineterminator="\n")


def validate_parsed(df_wide: pd.DataFrame) -> Tuple[pd.DataFrame, list]:
    """Keep dates with a trustworthy parse; return (kept_wide, rejected_dates)."""
    meta = {"Date", "Total"}
    state_cols = [c for c in df_wide.columns if c not in meta]
    n_states = df_wide[state_cols].notna().sum(axis=1)
    ok = (n_states >= MIN_STATES_WITH_ENERGY) & df_wide["Total"].notna() & (df_wide["Total"] > 0)
    rejected = df_wide.loc[~ok, "Date"].tolist()
    return df_wide[ok].copy(), rejected


def replace_wide(path: Path, df_wide: pd.DataFrame) -> pd.DataFrame:
    """Drop rows >= FIRST_FABRICATED_DATE and append real rows, keeping the file's columns."""
    orig = pd.read_csv(path)
    cols = list(orig.columns)
    kept = orig[pd.to_datetime(orig["Date"]) < pd.Timestamp(FIRST_FABRICATED_DATE)]
    new = df_wide[df_wide["Date"] >= FIRST_FABRICATED_DATE].reindex(columns=cols)
    out = pd.concat([kept, new], ignore_index=True)
    out["Date"] = pd.to_datetime(out["Date"])
    out = out.sort_values("Date").drop_duplicates("Date", keep="last")
    out["Date"] = out["Date"].dt.strftime("%Y-%m-%d")
    _write_csv(out, path)
    return out


def replace_state_mu_1(path: Path, df_long: pd.DataFrame) -> pd.DataFrame:
    """Rebuild state_mu_1 rows; every day lists the same entity set as earlier real days."""
    orig = pd.read_csv(path)
    cols = list(orig.columns)
    kept = orig[orig["date"] < FIRST_FABRICATED_DATE]
    template = kept[kept["date"] == kept["date"].max()][["Region", "States"]]
    new = df_long[df_long["date"] >= FIRST_FABRICATED_DATE]

    frames = []
    for day, grp in new.groupby("date"):
        day_rows = template.merge(grp.drop(columns=["Region"]), on="States", how="left")
        day_rows["date"] = day
        day_rows["Shortage during maximum Demand(MW)"] = day_rows["Shortage during maximum Demand(MW)"].fillna(0.0)
        frames.append(day_rows[cols])  # non-state utilities (Railways, BALCO, ...) are not in the template
    out = pd.concat([kept] + frames, ignore_index=True)
    _write_csv(out, path)
    return out


def replace_state_mu_2(path: Path, df_gen: pd.DataFrame) -> pd.DataFrame:
    orig = pd.read_csv(path)
    cols = list(orig.columns)
    kept = orig[orig["date"] < FIRST_FABRICATED_DATE]
    new = df_gen[df_gen["date"] >= FIRST_FABRICATED_DATE].reindex(columns=cols)
    new = new.sort_values(["date", "source"])
    out = pd.concat([kept, new], ignore_index=True)
    _write_csv(out, path)
    return out


def replace_long_state_mu2(path: Path, state_mu_2: pd.DataFrame) -> pd.DataFrame:
    """Re-derive long format only for the replaced dates; earlier rows are left untouched."""
    orig = pd.read_csv(path)
    cols = list(orig.columns)
    kept = orig[orig["date"] < FIRST_FABRICATED_DATE]
    new_src = state_mu_2[state_mu_2["date"] >= FIRST_FABRICATED_DATE]
    long_new = new_src.melt(id_vars=["source", "date"], value_vars=GEN_REGION_COLS,
                            var_name="region", value_name="regional_generation_mu")
    long_new["region"] = long_new["region"].str.lower()
    long_new = long_new.dropna(subset=["regional_generation_mu"])
    long_new = long_new.sort_values(["date", "region", "source"])[cols]
    out = pd.concat([kept, long_new], ignore_index=True)
    _write_csv(out, path)
    return out


def run(dry_run: bool = False) -> dict:
    df_wide, df_long, df_gen = parse_all_psp_files()
    df_wide, rejected = validate_parsed(df_wide)
    good_dates = set(df_wide["Date"])
    df_long = df_long[df_long["date"].isin(good_dates)]
    df_gen = df_gen[df_gen["date"].isin(good_dates)]
    if rejected:
        logger.warning("Rejected unparseable/implausible dates: %s", rejected)

    real_dates = sorted(d for d in good_dates if d >= FIRST_FABRICATED_DATE)
    summary = {"real_dates": len(real_dates), "first": real_dates[0] if real_dates else None,
               "last": real_dates[-1] if real_dates else None, "rejected": rejected}
    if dry_run or not real_dates:
        return summary

    replace_wide(DEMAND_CSV_MAIN, df_wide)
    replace_wide(DEMAND_CSV_MIRROR, df_wide)
    replace_state_mu_1(STATE_MU_1_PATH, df_long)
    sm2 = replace_state_mu_2(STATE_MU_2_PATH, df_gen)
    replace_long_state_mu2(LONG_STATE_MU2_PATH, sm2)
    return summary


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    logger.info("%s", run(dry_run=args.dry_run))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
